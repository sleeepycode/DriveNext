begin;
alter table public.cars add column if not exists address text not null default 'Москва, ул. Авиамоторная, 8';
alter table public.cars add column if not exists description text not null default 'Комфортный автомобиль для городских и загородных поездок.';
alter table public.cars add column if not exists insurance_daily integer not null default 500 check (insurance_daily >= 0);
alter table public.cars add column if not exists deposit integer not null default 5000 check (deposit >= 0);
create table if not exists public.bookings (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 car_id bigint not null references public.cars(id), request_id uuid not null,
 brand text not null, model text not null, daily_price integer not null, transmission text not null, fuel text not null, image_key text not null, address text not null,
 start_at timestamptz not null, end_at timestamptz not null check(end_at > start_at),
 driver_name text not null, license_number text not null,
 rent_total bigint not null, insurance_total bigint not null, deposit integer not null,
 status text not null default 'approved' check(status in ('approved','cancelled')),
 created_at timestamptz not null default now(), unique(user_id, request_id)
);
create index if not exists drivenext_bookings_car_time on public.bookings(car_id,start_at,end_at);
create index if not exists drivenext_bookings_user on public.bookings(user_id);
alter table public.bookings enable row level security;
revoke all on public.bookings from anon, authenticated;
grant select on public.bookings to authenticated;
drop policy if exists drivenext_bookings_read on public.bookings;
create policy drivenext_bookings_read on public.bookings for select to authenticated using (user_id = (select auth.uid()));
create or replace function public.drivenext_book_car(p_car bigint,p_start timestamptz,p_end timestamptz,p_driver text,p_license text,p_request uuid)
returns bigint language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); c public.cars%rowtype; n bigint; result_id bigint;
begin
 if u is null or p_request is null then raise exception 'INVALID_RENTAL'; end if;
 -- Lock the car before checking overlaps: concurrent requests cannot double-book it.
 select * into c from public.cars where id=p_car for update;
 select id into result_id from public.bookings where user_id=u and request_id=p_request;
 if found then return result_id; end if;
 if c.id is null or not c.available then raise exception 'CAR_UNAVAILABLE'; end if;
 if p_start is null or p_end is null or p_start < now() or p_end <= p_start or p_end-p_start > interval '365 days'
 or p_driver is null or char_length(trim(p_driver)) not between 1 and 200 or p_license is null or char_length(p_license) <> 10 or p_license ~ '[[:space:]]' then raise exception 'INVALID_RENTAL'; end if;
 if not exists(select 1 from public.profiles where id=u and registration_complete) then raise exception 'INVALID_RENTAL'; end if;
 if exists(select 1 from public.bookings where car_id=p_car and status='approved' and start_at<p_end and end_at>p_start) then raise exception 'CAR_BUSY'; end if;
 n := ceil(extract(epoch from (p_end-p_start))/86400)::bigint;
 insert into public.bookings(user_id,car_id,request_id,brand,model,daily_price,transmission,fuel,image_key,address,start_at,end_at,driver_name,license_number,rent_total,insurance_total,deposit)
 values(u,c.id,p_request,c.brand,c.model,c.daily_price,c.transmission,c.fuel,c.image_key,c.address,p_start,p_end,trim(p_driver),p_license,n*c.daily_price,n*c.insurance_daily,c.deposit) returning id into result_id;
 return result_id;
end; $$;
create or replace function public.drivenext_cancel_booking(p_id bigint) returns void language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null then raise exception 'INVALID_RENTAL'; end if;
 update public.bookings set status='cancelled' where id=p_id and user_id=auth.uid() and status='approved' and end_at>now();
 if not found and not exists(select 1 from public.bookings where id=p_id and user_id=auth.uid() and status='cancelled') then raise exception 'INVALID_RENTAL'; end if;
end; $$;
revoke all on function public.drivenext_book_car(bigint,timestamptz,timestamptz,text,text,uuid) from public,anon,authenticated;
revoke all on function public.drivenext_cancel_booking(bigint) from public,anon,authenticated;
grant execute on function public.drivenext_book_car(bigint,timestamptz,timestamptz,text,text,uuid) to authenticated;
grant execute on function public.drivenext_cancel_booking(bigint) to authenticated;
commit;
