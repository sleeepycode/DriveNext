begin;
create table if not exists public.cars (
    id bigint generated by default as identity primary key,
    brand text not null,
    model text not null,
    daily_price integer not null check (daily_price > 0),
    transmission text not null,
    fuel text not null,
    image_key text not null,
    available boolean not null default true,
    unique (brand, model)
);
alter table public.cars enable row level security;
revoke all on public.cars from anon, authenticated;
grant select on public.cars to authenticated;
drop policy if exists drivenext_cars_read on public.cars;
create policy drivenext_cars_read on public.cars for select to authenticated using (available);
-- Серверный поиск: регистр не важен, %, _ и кавычки трактуются как обычный текст.
create or replace function public.drivenext_search_cars(search_text text default '')
returns setof public.cars language sql stable security invoker set search_path = '' as $$
    select c.* from public.cars c
    where c.available and (
        strpos(lower(c.brand || ' ' || c.model), lower(trim(coalesce(search_text, '')))) > 0
        or strpos(lower(c.model || ' ' || c.brand), lower(trim(coalesce(search_text, '')))) > 0
    ) order by c.id;
$$;
revoke all on function public.drivenext_search_cars(text) from public, anon, authenticated;
grant execute on function public.drivenext_search_cars(text) to authenticated;
